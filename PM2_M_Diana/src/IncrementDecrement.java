public class IncrementDecrement {
    public static void msin (String[] args){
        int i = 1;
        System.out.println("i : " + i);
        // Pre-Increment
        System.out.println("++i : " + ++i);
        //Post-Increment
        System.out.println("i++ : " + i++);
        System.out.println("i : " + i);
        // Pre-Decrement
        System.out.println("--i : " + --i);
        // Post-Decrement
        System.out.println("i-- : " + i--);
        System.out.println("i ; " + i);
    }
}